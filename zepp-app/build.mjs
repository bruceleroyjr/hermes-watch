// Writes app-side/token.js (git-ignored) from ../config.json, so the watch token
// never lands in git. Run before `zeus build` / `zeus preview`:
//   node build.mjs            (or WATCH_CONFIG=<path> node build.mjs)
import { readFileSync, writeFileSync } from 'fs'
import { fileURLToPath } from 'url'
import { dirname, join } from 'path'

const here = dirname(fileURLToPath(import.meta.url))
const configFile = process.env.WATCH_CONFIG || join(here, '..', 'config.json')
const { token } = JSON.parse(readFileSync(configFile, 'utf8'))
if (!token) throw new Error(`no "token" in ${configFile}`)
const relay = process.env.WATCH_RELAY_URL || JSON.parse(readFileSync(configFile, 'utf8')).relayUrl
if (!relay) throw new Error(`set "relayUrl" in ${configFile} (e.g. https://<pc>.<tailnet>.ts.net:8453)`)
writeFileSync(join(here, 'app-side', 'token.js'),
  `// Generated by build.mjs - do not commit.\nexport const TOKEN = ${JSON.stringify(token)}\nexport const RELAY = ${JSON.stringify(relay)}\n`)
console.log(`app-side/token.js written for ${relay}`)
